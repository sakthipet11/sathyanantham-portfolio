from typing import Optional, List, Dict, Any
from fastapi import APIRouter, HTTPException, Body
from pydantic import BaseModel

from backend.python.services.ai_job_copilot_service import ai_job_copilot_service
from backend.python.services.audit_governance_service import audit_governance_service

router = APIRouter(prefix="/api/v2/copilot", tags=["copilot_v2"])

class CopilotChatRequest(BaseModel):
    message: str
    context: Optional[Dict[str, Any]] = None

class CopilotActionRequest(BaseModel):
    action_id: str
    target_ids: Optional[List[str]] = None

@router.post("/chat")
async def chat_with_copilot(req: CopilotChatRequest):
    """Processes natural language job search commands and returns interactive reasoning and action cards."""
    if not req.message.strip():
        raise HTTPException(status_code=400, detail="Message cannot be empty")
    
    result = await ai_job_copilot_service.process_chat_message_async(req.message, context=req.context)
    return {"status": "success", "data": result}

